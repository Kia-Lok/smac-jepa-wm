#!/usr/bin/env bash
# ============================================================================
# CORRECTED EVALUATION FOR AVAILABLE EXPERIMENTS FROM EXP01–EXP15
#
# Exact experiment folders expected under CHECKPOINT_ROOT:
#
#   exp 01/checkpoint.pt
#   exp 02/checkpoint.pt
#   exp 03/checkpoint.pt
#   exp 04/checkpoint.pt
#   exp 07/checkpoint.pt
#   exp 09/checkpoint.pt
#   exp 10/checkpoint.pt
#   exp 11/checkpoint.pt
#   exp 12/checkpoint.pt
#   exp 13/checkpoint.pt
#   exp 14/checkpoint.pt
#   exp 15/checkpoint.pt
#
# Deliberately excluded because they do not exist:
#   exp 05, exp 06, exp 08
#
# Run this from the smac-dreamer directory containing those folders, or set:
#   CHECKPOINT_ROOT=/path/to/smac-dreamer
#
# The script:
#   - validates all 12 expected checkpoint.pt files;
#   - writes a checkpoint manifest;
#   - evaluates them using the same corrected padding-aware H5 protocol;
#   - automatically applies R2 latent normalization only where configured;
#   - retains latent, presence, action-shuffle, memory-ablation,
#     autonomous-mask, native decoder, probe decoder, and throughput metrics.
# ============================================================================

set -euo pipefail

CHECKPOINT_ROOT="${CHECKPOINT_ROOT:-$(pwd)}"
OUT_DIR="${OUT_DIR:-${CHECKPOINT_ROOT}/eval_exp01_to_exp15_except_05_06_08_corrected}"

MAX_BATCHES="${MAX_BATCHES:-500}"
DIAGNOSTIC_MAX_BATCHES="${DIAGNOSTIC_MAX_BATCHES:-100}"
PROBE_EPOCHS="${PROBE_EPOCHS:-20}"
PROBE_MAX_BATCHES="${PROBE_MAX_BATCHES:-300}"
PROBE_SAMPLES_PER_EPOCH="${PROBE_SAMPLES_PER_EPOCH:-20000}"
BATCH_SIZE="${BATCH_SIZE:-16}"
NUM_WORKERS="${NUM_WORKERS:-4}"
FORCE_RETRAIN_PROBE="${FORCE_RETRAIN_PROBE:-0}"

# Exact experiments to evaluate.
EXPERIMENTS=(
  "01"
  "02"
  "03"
  "04"
  "07"
  "09"
  "10"
  "11"
  "12"
  "13"
  "14"
  "15"
)

resolve_code_root() {
  local candidates=()

  if [[ -n "${CODE_ROOT:-}" ]]; then
    candidates+=("$CODE_ROOT")
  fi

  candidates+=(
    "$CHECKPOINT_ROOT"
    "/home/jovyan/smac-jepa-wm"
    "/home/jovyan/workspace/smac-jepa-wm"
    "/home/jovyan/workspace/smac-dreamer"
    "/home/jovyan/smac-dreamer"
  )

  local candidate=""
  for candidate in "${candidates[@]}"; do
    if [[ -d "$candidate/smac_jepa" \
          && -f "$candidate/splits/generated_seed4_mapdims_only.json" ]]; then
      (
        cd "$candidate"
        pwd
      )
      return 0
    fi
  done

  echo "ERROR: could not find a code repository containing both:" >&2
  echo "  smac_jepa/" >&2
  echo "  splits/generated_seed4_mapdims_only.json" >&2
  echo >&2
  echo "Set CODE_ROOT explicitly, for example:" >&2
  echo "  CODE_ROOT=/home/jovyan/smac-jepa-wm $0" >&2
  return 1
}

CODE_ROOT="$(resolve_code_root)"
mkdir -p "$OUT_DIR"

declare -a CHECKPOINT_PATHS=()
declare -a CHECKPOINT_ARGS=()
declare -a MISSING=()

echo "============================================================"
echo "Corrected evaluation"
echo "Checkpoint root: $CHECKPOINT_ROOT"
echo "Code root:       $CODE_ROOT"
echo "Output:          $OUT_DIR"
echo "Experiments:     ${EXPERIMENTS[*]}"
echo "Skipped:         05 06 08"
echo "============================================================"

for number in "${EXPERIMENTS[@]}"; do
  folder="${CHECKPOINT_ROOT}/exp ${number}"
  checkpoint="${folder}/checkpoint.pt"

  if [[ -f "$checkpoint" ]]; then
    absolute_checkpoint="$(
      cd "$folder"
      printf "%s/checkpoint.pt\n" "$(pwd)"
    )"

    CHECKPOINT_PATHS+=("$absolute_checkpoint")
    CHECKPOINT_ARGS+=(--checkpoint "$absolute_checkpoint")

    printf "FOUND   exp %s  %s\n" "$number" "$absolute_checkpoint"
  else
    MISSING+=("exp ${number}")
    printf "MISSING exp %s  %s\n" "$number" "$checkpoint"
  fi
done

if [[ ${#MISSING[@]} -gt 0 ]]; then
  echo
  echo "ERROR: expected checkpoint folders are missing:"
  printf "  %s/checkpoint.pt\n" "${MISSING[@]}"
  echo
  echo "Expected exact naming format:"
  echo "  ${CHECKPOINT_ROOT}/exp 01/checkpoint.pt"
  echo "  ..."
  echo "  ${CHECKPOINT_ROOT}/exp 15/checkpoint.pt"
  echo
  echo "Only exp 05, exp 06, and exp 08 are intentionally excluded."
  exit 1
fi

MANIFEST_CSV="${OUT_DIR}/checkpoint_manifest.csv"

python - "$MANIFEST_CSV" "${CHECKPOINT_PATHS[@]}" <<'PY'
from pathlib import Path
import csv
import re
import sys
import torch

output = Path(sys.argv[1])
paths = [Path(value).resolve() for value in sys.argv[2:]]

rows = []

for path in paths:
    match = re.fullmatch(
        r"exp\s+(\d+)",
        path.parent.name.lower(),
    )
    experiment_number = (
        int(match.group(1))
        if match
        else None
    )

    try:
        try:
            checkpoint = torch.load(
                path,
                map_location="cpu",
                weights_only=False,
            )
        except TypeError:
            checkpoint = torch.load(
                path,
                map_location="cpu",
            )
    except Exception as exc:
        raise SystemExit(
            f"Unreadable checkpoint {path}: "
            f"{type(exc).__name__}: {exc}"
        )

    config = checkpoint.get(
        "resolved_config",
        checkpoint.get("config", {}),
    )

    required = ["model_state"]
    missing = [
        key
        for key in required
        if key not in checkpoint
    ]
    if missing:
        raise SystemExit(
            f"Checkpoint {path} lacks required keys: {missing}"
        )

    row = {
        "experiment": (
            f"exp {experiment_number:02d}"
            if experiment_number is not None
            else path.parent.name
        ),
        "folder": path.parent.name,
        "checkpoint": str(path),
        "epoch": int(checkpoint.get("epoch", -1)),
        "global_step": int(
            checkpoint.get("global_step", -1)
        ),
        "training_regime": config.get(
            "training_regime", ""
        ),
        "rollout_horizon": config.get(
            "rollout_horizon", ""
        ),
        "target_mode": config.get(
            "target_mode", ""
        ),
        "action_conditioned_memory": config.get(
            "action_conditioned_memory", ""
        ),
        "r2_latent_normalize": config.get(
            "r2_latent_normalize", False
        ),
    }
    rows.append(row)

    print(
        f"VERIFIED {row['experiment']}: "
        f"epoch={row['epoch']} "
        f"step={row['global_step']} "
        f"regime={row['training_regime']} "
        f"r2_norm={row['r2_latent_normalize']} "
        f"path={path}"
    )

rows.sort(key=lambda row: row["experiment"])

output.parent.mkdir(parents=True, exist_ok=True)
with output.open("w", newline="") as handle:
    writer = csv.DictWriter(
        handle,
        fieldnames=list(rows[0].keys()),
    )
    writer.writeheader()
    writer.writerows(rows)

print(f"Wrote checkpoint manifest: {output}")
PY

