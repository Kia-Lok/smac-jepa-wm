select_best_checkpoint() {
  local run_dir="$1"
  local experiment_name="$2"
  local target_epoch="$3"

  python - "$run_dir" "$experiment_name" "$target_epoch" <<'PY'
from pathlib import Path
import sys
import torch

run_dir = Path(sys.argv[1])
name = sys.argv[2]
target_epoch = int(sys.argv[3])

candidates = []
if run_dir.exists():
    candidates.extend(run_dir.glob("checkpoint_epoch_*.pt"))
    latest = run_dir / "checkpoint.pt"
    if latest.exists():
        candidates.append(latest)

candidates = sorted(set(path.resolve() for path in candidates))

if not candidates:
    print(
        f"[{name}] No checkpoint files found under {run_dir}",
        file=sys.stderr,
    )
    raise SystemExit(1)

valid = []

for path in candidates:
    try:
        try:
            checkpoint = torch.load(
                path,
                map_location="cpu",
                weights_only=False,
            )
        except TypeError:
            checkpoint = torch.load(path, map_location="cpu")

        epoch = int(checkpoint.get("epoch", -1))
        global_step = int(checkpoint.get("global_step", -1))

        if epoch < 0 and path.name.startswith("checkpoint_epoch_"):
            try:
                epoch = int(path.stem.rsplit("_", 1)[-1])
            except ValueError:
                pass

        valid.append(
            (
                epoch,
                global_step,
                path.stat().st_mtime_ns,
                path,
            )
        )

        print(
            f"[{name}] valid candidate: "
            f"epoch={epoch} step={global_step} path={path}",
            file=sys.stderr,
        )
    except Exception as exc:
        print(
            f"[{name}] CORRUPT/UNREADABLE candidate skipped: "
            f"{path} ({type(exc).__name__}: {exc})",
            file=sys.stderr,
        )

if not valid:
    print(
        f"[{name}] Checkpoint files exist, but none can be loaded.",
        file=sys.stderr,
    )
    raise SystemExit(2)

epoch, global_step, _, selected = max(
    valid,
    key=lambda item: (item[0], item[1], item[2]),
)

status = (
    "FINAL"
    if epoch >= target_epoch
    else f"PARTIAL (saved epoch {epoch} of {target_epoch})"
)

print(
    f"[{name}] SELECTED {status}: "
    f"epoch={epoch} step={global_step} path={selected}",
    file=sys.stderr,
)

print(selected)
PY
}

